// loadSessionReads parses access.log and returns the set of note IDs read after the most recent
// "--global" sentinel for the current process's parent PID. Returns an empty map on any error.
func loadSessionReads(cfgDir string) map[string]bool {
	data, err := os.ReadFile(filepath.Join(cfgDir, "access.log"))
	if err != nil {
		return map[string]bool{}
	}
	ppid := strconv.Itoa(os.Getppid())
	var sessionStart int = -1
	lines := strings.Split(strings.TrimRight(string(data), "\n"), "\n")
	for i, line := range lines {
		parts := strings.Fields(line)
		// format: <RFC3339> <PPID> show <id>
		if len(parts) == 4 && parts[1] == ppid && parts[3] == "--global" {
			sessionStart = i
		}
	}
	result := map[string]bool{}
	if sessionStart < 0 {
		return result
	}
	for _, line := range lines[sessionStart+1:] {
		parts := strings.Fields(line)
		if len(parts) == 4 && parts[1] == ppid && parts[2] == "show" {
			result[parts[3]] = true
		}
	}
	return result
}

// resolveCfgDir returns the nn config directory from NN_CONFIG_DIR, XDG_CONFIG_HOME, or ~/.config/nn.
func resolveCfgDir() string {
	if d := os.Getenv("NN_CONFIG_DIR"); d != "" {
		return d
	}
	xdg := os.Getenv("XDG_CONFIG_HOME")
	if xdg == "" {
		home, _ := os.UserHomeDir()
		xdg = filepath.Join(home, ".config")
	}
	return filepath.Join(xdg, "nn")
}

// appendAccessLog records a note retrieval to the advisory access log.
// Failures are silently ignored — the log is advisory only.
// Each entry records the current process's parent PID so concurrent shell sessions
// can be distinguished when deriving session read-state.
func appendAccessLog(cfgDir, id string) {
	_ = os.MkdirAll(cfgDir, 0o755)
	logPath := filepath.Join(cfgDir, "access.log")

	// Prune entries older than 7 days, but only when file exceeds 50KB and last prune was >1h ago.
	cutoff := time.Now().UTC().Add(-7 * 24 * time.Hour)
	markerPath := logPath + ".pruned"
	if info, statErr := os.Stat(logPath); statErr == nil && info.Size() > 50*1024 {
		recentlyPruned := false
		if markerData, merr := os.ReadFile(markerPath); merr == nil {
			if t, perr := time.Parse(time.RFC3339, strings.TrimSpace(string(markerData))); perr == nil {
				if time.Since(t) < 24*time.Hour {
					recentlyPruned = true
				}
			}
		}
		if !recentlyPruned {
			if data, err := os.ReadFile(logPath); err == nil {
				var kept []string
				for _, line := range strings.Split(strings.TrimRight(string(data), "\n"), "\n") {
					if line == "" {
						continue
					}
					parts := strings.Fields(line)
					if len(parts) >= 1 {
						if t, err := time.Parse(time.RFC3339, parts[0]); err == nil && t.Before(cutoff) {
							continue
						}
					}
					kept = append(kept, line)
				}
				_ = os.WriteFile(logPath, []byte(strings.Join(kept, "\n")+"\n"), 0o644)
				_ = os.WriteFile(markerPath, []byte(time.Now().UTC().Format(time.RFC3339)), 0o644)
			}
		}
	}

	f, err := os.OpenFile(logPath, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	defer f.Close()
	fmt.Fprintf(f, "%s %d show %s\n", time.Now().UTC().Format(time.RFC3339), os.Getppid(), id)
}

// governingProtocolsFromEngine returns the protocol notes that govern targetID,
// derived from the engine's governs_note predicate (direct + whole-tree
// representation + refines/extends specialization). This is the single source of
// truth for governance, replacing the ad-hoc findGoverningProtocols traversal.
// governanceEngine bundles a saturated rules engine with the note lookup its
// governs_note facts resolve against. Build it once per command with
// buildGovernanceEngine, then query per note with governedBy — the datalog
// fixpoint (which for representation subgraphs runs a transitive closure over
// all facts) must not be re-evaluated per shown note.
type governanceEngine struct {
	engine *rules.Engine
	byID   map[string]*note.Note
}

// buildGovernanceEngine loads facts + builtin rules and evaluates the fixpoint
// once. Returns nil on parse/eval failure (callers treat nil as "no governance
// derivable", matching the prior per-call error behavior).
func buildGovernanceEngine(all []*note.Note) *governanceEngine {
	byID := make(map[string]*note.Note, len(all))
	for _, n := range all {
		byID[n.ID] = n
	}
	e := rules.NewEngine()
	for _, f := range rules.FactsFromNotes(all) {
		e.AddFact(f)
	}
	builtin, err := rules.ParseProgram(rules.BuiltinRules())
	if err != nil {
		return nil
	}
	e.AddRules(builtin)
	if err := e.EvalFor("governs_note"); err != nil {
		return nil
	}
	return &governanceEngine{engine: e, byID: byID}
}

// governingProtocolsFromEngine builds a governance engine and queries it for a
// single note. Prefer buildGovernanceEngine + governedBy when resolving several
// notes so the fixpoint is evaluated once; this one-shot form remains for
// callers (and tests) that resolve a single note against a bespoke note set.
func governingProtocolsFromEngine(targetID string, all []*note.Note) []*note.Note {
	return governedBy(buildGovernanceEngine(all), targetID)
}

// governedBy returns the protocol notes that govern targetID, querying the
// already-saturated engine (no re-evaluation). A nil ge yields no protocols.
func governedBy(ge *governanceEngine, targetID string) []*note.Note {
	if ge == nil {
		return nil
	}
	seen := make(map[string]bool)
	var result []*note.Note
	for _, f := range ge.engine.Query("governs_note") {
		if len(f.Args) >= 2 && f.Args[1] == targetID {
			pID := f.Args[0]
			if seen[pID] {
				continue
			}
			if p := ge.byID[pID]; p != nil {
				seen[pID] = true
				result = append(result, p)
			}
		}
	}
	sort.Slice(result, func(i, j int) bool { return result[i].ID < result[j].ID })
	return result
}

// resolveNote finds a note by exact ID or case-insensitive title substring.
// The special query "daily" resolves to today's Daily: YYYY-MM-DD note, creating it if absent.
func resolveNote(state *rootState, query string) (*note.Note, error) {
	if strings.ToLower(query) == "daily" {
		return resolveDailyNote(state)
	}
	n, err := state.backend.Read(query)
	if err == nil {
		return n, nil
	}
	all, listErr := state.backend.List()
	if listErr != nil {
		return nil, fmt.Errorf("%w", err)
	}
	type match struct{ id, title string }
	var matches []match
	for _, candidate := range all {
		if strings.Contains(strings.ToLower(candidate.Title), strings.ToLower(query)) {
			matches = append(matches, match{candidate.ID, candidate.Title})
		}
	}
	switch len(matches) {
	case 0:
		return nil, fmt.Errorf("no note found matching %q", query)
	case 1:
		return state.backend.Read(matches[0].id)
	default:
		return nil, fmt.Errorf("ambiguous query %q — %d matches; use full ID", query, len(matches))
	}
}

// resolveDailyNote finds or creates today's Daily: YYYY-MM-DD note.
// Created notes are tagged "daily" and expire in 7 days.
func resolveDailyNote(state *rootState) (*note.Note, error) {
	today := nowFn().Format("2006-01-02")
	todayTitle := "Daily: " + today

	all, err := state.backend.List()
	if err != nil {
		return nil, fmt.Errorf("daily: list: %w", err)
	}
	for _, candidate := range all {
		if candidate.Title == todayTitle {
			return state.backend.Read(candidate.ID)
		}
	}

	yesterday := nowFn().AddDate(0, 0, -1).Format("2006-01-02")
	yesterdayTitle := "Daily: " + yesterday
	var body string
	for _, candidate := range all {
		if candidate.Title == yesterdayTitle {
			yn, readErr := state.backend.Read(candidate.ID)
			if readErr == nil && yn.Body != "" {
				body = "### Yesterday\n\n" + stripDoneSection(yn.Body)
			}
			break
		}
	}

	expires := time.Now().UTC().AddDate(0, 0, 7)
	now := time.Now().UTC()
	n := &note.Note{
		ID:       note.GenerateID(),
		Title:    todayTitle,
		Type:     note.TypeObservation,
		Status:   note.StatusDraft,
		Tags:     []string{"daily"},
		Expires:  &expires,
		Created:  now,
		Modified: now,
		Body:     body,
	}
	if err := state.backend.Write(n); err != nil {
		return nil, fmt.Errorf("daily: create: %w", err)
	}
	return n, nil
}

// stripCarryForwardSections removes sections that must not accumulate across days.
// It strips ## Done (completed work) and ### Yesterday (already-carried content)
// so each day's seed is clean.
func stripDoneSection(body string) string {
	lines := strings.Split(body, "\n")
	var out []string
	inStripped := false
	for _, line := range lines {
		if strings.HasPrefix(line, "## Done") || strings.HasPrefix(line, "### Yesterday") {
			inStripped = true
			continue
		}
		if inStripped {
			// A same-or-higher-level heading ends the stripped section.
			if strings.HasPrefix(line, "## ") || strings.HasPrefix(line, "### ") {
				inStripped = false
			} else {
				continue
			}
		}
		out = append(out, line)
	}
	return strings.TrimRight(strings.Join(out, "\n"), "\n")
}

// findVirtualProtocol returns the virtualProtocol whose ID matches query exactly,
// or nil if no virtual protocol matches.
func findVirtualProtocol(query string) *virtualProtocol {
	for i, vp := range virtualGlobalProtocols {
		if vp.ID == query {
			return &virtualGlobalProtocols[i]
		}
	}
	return nil
}

// findBacklinkers returns all notes in all that link to targetID (any link type).
func findBacklinkers(targetID string, all []*note.Note) []*note.Note {
	var result []*note.Note
	for _, n := range all {
		for _, lnk := range n.Links {
			if lnk.TargetID == targetID {
				result = append(result, n)
				break
			}
		}
	}
	return result
}

// injectFreshness inserts a "freshness: <tier>" line after the closing "---" of the
// YAML frontmatter in a marshaled note string.
func injectFreshness(raw string, modified time.Time) string {
	const sep = "---\n"
	// Find the second "---\n" which closes the frontmatter.
	first := strings.Index(raw, sep)
	if first < 0 {
		return raw
	}
	second := strings.Index(raw[first+len(sep):], sep)
	if second < 0 {
		return raw
	}
	insertAt := first + len(sep) + second + len(sep)
	label := freshnessLabel(modified)
	return raw[:insertAt] + "freshness: " + label + "\n" + raw[insertAt:]
}

// freshnessLabel returns a full staleness description including tier, human-readable age, and action hint.
// Tiers: fresh (< 3 days), aging (3–14 days), stale (> 14 days).
func freshnessLabel(modified time.Time) string {
	age := time.Since(modified)
	ageStr := humanAge(age)
	switch {
	case age < 3*24*time.Hour:
		return "fresh (" + ageStr + " — likely current)"
	case age < 14*24*time.Hour:
		return "aging (" + ageStr + " — may need recheck)"
	default:
		return "stale (" + ageStr + " — content may be outdated, verify before use)"
	}
}

// humanAge formats a duration as a short human-readable age string like "2 days ago" or "5 hours ago".
func humanAge(d time.Duration) string {
	switch {
	case d < time.Hour:
		m := int(d.Minutes())
		if m <= 1 {
			return "1 minute ago"
		}
		return fmt.Sprintf("%d minutes ago", m)
	case d < 24*time.Hour:
		h := int(d.Hours())
		if h == 1 {
			return "1 hour ago"
		}
		return fmt.Sprintf("%d hours ago", h)
	default:
		days := int(d.Hours() / 24)
		if days == 1 {
			return "1 day ago"
		}
		return fmt.Sprintf("%d days ago", days)
	}
}

// renderWithResolvedLinks replaces the raw ## Links section in marshaled note output
// with title-resolved link lines, and appends a ## Backlinks section.
// Target IDs are resolved via byID; unresolved IDs fall back to the bare ID.
func renderWithResolvedLinks(raw string, n *note.Note, byID map[string]*note.Note, backlinkers []*note.Note, showRules bool) string {
	var buf strings.Builder
	if len(n.Links) > 0 {
		const linkSection = "\n## Links\n\n"
		cut := strings.Index(raw, linkSection)
		if cut >= 0 {
			buf.WriteString(raw[:cut])
			buf.WriteString(linkSection)
			for _, lnk := range n.Links {
				title := lnk.TargetID
				if t, ok := byID[lnk.TargetID]; ok {
					title = t.Title
				}
				switch {
				case lnk.Type != "" && lnk.Status != "":
					fmt.Fprintf(&buf, "- [[%s|%s]] [%s] {%s} — %s\n", lnk.TargetID, title, lnk.Type, lnk.Status, lnk.Annotation)
				case lnk.Type != "":
					fmt.Fprintf(&buf, "- [[%s|%s]] [%s] — %s\n", lnk.TargetID, title, lnk.Type, lnk.Annotation)
				case lnk.Status != "":
					fmt.Fprintf(&buf, "- [[%s|%s]] {%s} — %s\n", lnk.TargetID, title, lnk.Status, lnk.Annotation)
				default:
					fmt.Fprintf(&buf, "- [[%s|%s]] — %s\n", lnk.TargetID, title, lnk.Annotation)
				}
			}
		} else {
			buf.WriteString(raw)
		}
	} else {
		buf.WriteString(raw)
	}
	if len(backlinkers) > 0 {
		fmt.Fprintf(&buf, "\n## Backlinks (%d)\n\n", len(backlinkers))
		for _, b := range backlinkers {
			for _, lnk := range b.Links {
				if lnk.TargetID == n.ID {
					switch {
					case lnk.Type != "" && lnk.Status != "":
						fmt.Fprintf(&buf, "- [[%s|%s]] [%s] {%s} — %s\n", b.ID, b.Title, lnk.Type, lnk.Status, lnk.Annotation)
					case lnk.Type != "":
						fmt.Fprintf(&buf, "- [[%s|%s]] [%s] — %s\n", b.ID, b.Title, lnk.Type, lnk.Annotation)
					case lnk.Status != "":
						fmt.Fprintf(&buf, "- [[%s|%s]] {%s} — %s\n", b.ID, b.Title, lnk.Status, lnk.Annotation)
					default:
						fmt.Fprintf(&buf, "- [[%s|%s]] — %s\n", b.ID, b.Title, lnk.Annotation)
					}
					break
				}
			}
		}
	}
	// The rule-violations section runs the full rules engine over the notebook,
	// so it is opt-in (--rules) to keep default nn show fast.
	if showRules {
		buf.WriteString(ruleViolationsSection(n, byID))
	}
	return buf.String()
}

// ruleViolationsSection evaluates the notebook's rules (built-in + nn-rule
// fences) and returns a "## Rule violations" section listing only the
// violations whose subject is note n. This closes the protocol-enforcement
// loop: a type:protocol note's nn-rule flags the notes it governs, and that is
// surfaced when those notes are shown. Returns "" when n has no violations.
func ruleViolationsSection(n *note.Note, byID map[string]*note.Note) string {
	all := make([]*note.Note, 0, len(byID))
	for _, m := range byID {
		all = append(all, m)
	}

	e := rules.NewEngine()
	for _, f := range rules.FactsFromNotes(all) {
		e.AddFact(f)
	}
	builtin, err := rules.ParseProgram(rules.BuiltinRules())
	if err != nil {
		return ""
	}
	e.AddRules(builtin)
	for _, m := range all {
		userRules, _ := rules.ExtractFenceRules(m.ID, m.Body)
		e.AddRules(userRules)
	}
	if err := e.Eval(); err != nil {
		// A non-stratifiable user ruleset must not break show output.
		return ""
	}

	var reasons []string
	for _, f := range e.Query("violation") {
		if len(f.Args) >= 2 && f.Args[0] == n.ID {
			reasons = append(reasons, f.Args[1])
		}
	}
	if len(reasons) == 0 {
		return ""
	}
	sort.Strings(reasons)

	var b strings.Builder
	fmt.Fprintf(&b, "\n## Rule violations (%d)\n\n", len(reasons))
	for _, r := range reasons {
		fmt.Fprintf(&b, "- %s\n", r)
	}
	return b.String()
}
