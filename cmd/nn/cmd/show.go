// virtualProtocol is a hardcoded protocol always included in nn show --global output.
// Body contains the full constraint text; AppliesWhen is a one-line application rule
// shown in compact --global output so the LLM can decide whether to fetch the full body.
type virtualProtocol struct {
	ID          string
	Title       string
	AppliesWhen string
	Body        string
}

// buildLinkTypeProtocolText generates the nn link type definitions block from note.LinkTypeDescriptions
// in canonical order, so show.go never drifts from the authoritative declarations in note.go.
func buildLinkTypeProtocolText() string {
	validTypes := strings.Join(note.LinkTypeOrder, "|")
	var sb strings.Builder
	sb.WriteString("Valid --type: " + validTypes + "\n\n")
	sb.WriteString("Link type definitions — choose the type whose definition matches the relationship you intend:\n")
	for _, t := range note.LinkTypeOrder {
		desc := note.LinkTypeDescriptions[t]
		warn := note.LinkTypeWarnings[t]
		if warn != "" {
			sb.WriteString("- `" + t + "` ⚠: " + desc + " — " + warn + ".\n")
		} else {
			sb.WriteString("- `" + t + "`: " + desc + "\n")
		}
	}
	sb.WriteString("\n")
	return sb.String()
}

